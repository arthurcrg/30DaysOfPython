print('Operações Básicas:')
print(2 + 3) # adição
print(5 - 2) # subtração
print(2 * 3) # multiplicação
print(10 / 2) # divisão
print(10 // 3) # divisão inteira
print(2 ** 2) # exponenciação
print(4 **(1 / 2)) # radiciação

print('Tipos de Variáveis:')
print(type(10)) # inteiro
print(type(10.5)) # float
print(type(1 + 2j)) # complexo
print(type('Bulbasaur')) # string
print(type(True)) #boleano
print(type([1, 2, 3])) # list
print(type((1, 2, 3))) #tuple
print(type({9.8, 3.4, 6.7})) # set
print(type({'nome': 'Bulbasaur', 'tipo': 'grama e venenoso'})) # dicionário
