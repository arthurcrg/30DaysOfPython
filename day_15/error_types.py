# There isn't much stuff to do here because I'm testing these in cmd, but I can at least list the main types of errors.
# 1. Syntax Error: Errors that occur when the Python parser cannot understand the code.
# 2. Name Error: Errors that occur when a variable is not found in the local or global scope.
# 3. Index Error: Errors that occur when an index is out of range for a sequence.
# 4. ModuleNotFoundError: Errors that occur when a module cannot be found or imported.
# 5. Attribute Error: Errors that occur when an attribute reference or assignment fails.
# 6. KeyError: Errors that occur when a dictionary key is not found.
# 7. TypeError: Errors that occur when an operation or function is applied to an object of inappropriate type.
# 8. ValueError: Errors that occur when a function receives an argument of the right type but inappropriate value.
# 9. ZeroDivisionError: Errors that occur when a division or modulo operation is performed with zero as the divisor.
